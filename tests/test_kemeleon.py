"""
Tests for Kemeleon encodings.

Roundtrip tests use ML-KEM keys/ciphertexts generated by kyber-py
(requires `pip install "kemeleon-py[dev]"`).
"""

import unittest

from kemeleon import Kemeleon_512, Kemeleon_768, Kemeleon_1024
from kemeleon import KemeleonR_512, KemeleonR_768, KemeleonR_1024
from kemeleon import Kemeleon, KemeleonR

from kyber_py.ml_kem import ML_KEM_512, ML_KEM_768, ML_KEM_1024

_Q = 3329
_N = 256

def _find_encodable_ek(kem, make_ek_fn, max_tries=10):
    """Generate fresh ek inputs until encode_ek succeeds (new input each try)."""
    for _ in range(max_tries):
        ek = make_ek_fn()
        eek = kem.encode_ek(ek)
        if eek is not None:
            return ek, eek
    raise RuntimeError(f"No encodable ek found after {max_tries} tries")


def _find_encodable_ctxt(kem, make_ctxt_fn, max_tries=10):
    """Generate fresh ciphertext inputs until encode_ctxt succeeds (new input each try)."""
    for _ in range(max_tries):
        c = make_ctxt_fn()
        ec = kem.encode_ctxt(c)
        if ec is not None:
            return c, ec
    raise RuntimeError(f"No encodable ctxt found after {max_tries} tries")

class TestOutputSizes(unittest.TestCase):
    """Verify encoded output lengths match the draft specification."""

    def _check_sizes(self, kem, kem_r, k, du, dv):
        # Main variant
        self.assertEqual(kem.eek_size(), 384 * k + 32)
        self.assertEqual(kem.ec_size(), 384 * (k + 1))
        # Rejection variant sizes
        num_bits = (_Q ** (k * _N) - 1).bit_length()
        r_bytes = (num_bits + 7) // 8
        self.assertEqual(kem_r.eek_size(), r_bytes + 32)
        self.assertEqual(kem_r.ec_size(), r_bytes + 32 * dv)

    def test_sizes_512(self):
        self._check_sizes(Kemeleon_512, KemeleonR_512, 2, 10, 4)
        self.assertEqual(Kemeleon_512.eek_size(), 800)
        self.assertEqual(Kemeleon_512.ec_size(), 1152)
        self.assertEqual(KemeleonR_512.eek_size(), 781)
        self.assertEqual(KemeleonR_512.ec_size(), 877)

    def test_sizes_768(self):
        self._check_sizes(Kemeleon_768, KemeleonR_768, 3, 10, 4)
        self.assertEqual(Kemeleon_768.eek_size(), 1184)
        self.assertEqual(Kemeleon_768.ec_size(), 1536)
        self.assertEqual(KemeleonR_768.eek_size(), 1156)
        self.assertEqual(KemeleonR_768.ec_size(), 1252)

    def test_sizes_1024(self):
        self._check_sizes(Kemeleon_1024, KemeleonR_1024, 4, 11, 5)
        self.assertEqual(Kemeleon_1024.eek_size(), 1568)
        self.assertEqual(Kemeleon_1024.ec_size(), 1920)
        self.assertEqual(KemeleonR_1024.eek_size(), 1530)
        self.assertEqual(KemeleonR_1024.ec_size(), 1658)

class TestWithKyberPy(unittest.TestCase):
    """Roundtrip tests using ML-KEM keys and ciphertexts from kyber-py."""

    def _generic_ek_roundtrip(self, ml_kem, kemeleon, count=3):
        for _ in range(count):
            ek, _ = ml_kem.keygen()
            eek = kemeleon.encode_ek(ek)
            self.assertEqual(len(eek), kemeleon.eek_size())
            self.assertEqual(kemeleon.decode_ek(eek), ek)

    def _generic_ctxt_roundtrip(self, ml_kem, kemeleon, count=3):
        for _ in range(count):
            ek, dk = ml_kem.keygen()
            _, c = ml_kem.encaps(ek)
            ec = kemeleon.encode_ctxt(c)
            self.assertEqual(len(ec), kemeleon.ec_size())
            self.assertEqual(kemeleon.decode_ctxt(ec), c)

    def _generic_ek_r_roundtrip(self, ml_kem, kemeleon, count=3):
        for _ in range(count):
            ek, eek = _find_encodable_ek(kemeleon, lambda: ml_kem.keygen()[0])
            self.assertEqual(len(eek), kemeleon.eek_size())
            self.assertEqual(kemeleon.decode_ek(eek), ek)

    def _generic_ctxt_r_roundtrip(self, ml_kem, kemeleon, count=3):
        for _ in range(count):
            ek, _ = ml_kem.keygen()
            c, ec = _find_encodable_ctxt(kemeleon, lambda: ml_kem.encaps(ek)[1])
            self.assertEqual(len(ec), kemeleon.ec_size())
            self.assertEqual(kemeleon.decode_ctxt(ec), c)

    def test_ek_512(self):
        self._generic_ek_roundtrip(ML_KEM_512, Kemeleon_512)

    def test_ctxt_512(self):
        self._generic_ctxt_roundtrip(ML_KEM_512, Kemeleon_512)

    def test_ek_r_512(self):
        self._generic_ek_r_roundtrip(ML_KEM_512, KemeleonR_512)

    def test_ctxt_r_512(self):
        self._generic_ctxt_r_roundtrip(ML_KEM_512, KemeleonR_512)

    def test_ek_768(self):
        self._generic_ek_roundtrip(ML_KEM_768, Kemeleon_768)

    def test_ctxt_768(self):
        self._generic_ctxt_roundtrip(ML_KEM_768, Kemeleon_768)

    def test_ek_r_768(self):
        self._generic_ek_r_roundtrip(ML_KEM_768, KemeleonR_768)

    def test_ctxt_r_768(self):
        self._generic_ctxt_r_roundtrip(ML_KEM_768, KemeleonR_768)

    def test_ek_1024(self):
        self._generic_ek_roundtrip(ML_KEM_1024, Kemeleon_1024)

    def test_ctxt_1024(self):
        self._generic_ctxt_roundtrip(ML_KEM_1024, Kemeleon_1024)

    def test_ek_r_1024(self):
        self._generic_ek_r_roundtrip(ML_KEM_1024, KemeleonR_1024)

    def test_ctxt_r_1024(self):
        self._generic_ctxt_r_roundtrip(ML_KEM_1024, KemeleonR_1024)


if __name__ == "__main__":
    unittest.main()
